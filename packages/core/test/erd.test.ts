import { PGlite } from '@electric-sql/pglite';
import { describe, expect, it } from 'vitest';
import {
  addFkColumns,
  buildJunction,
  emptySchema,
  erdToDdl,
  formatColumn,
  needsQuote,
  newColumn,
  parseColumn,
  propagatePk,
  quoteIdent,
  topoOrder,
  umlTypeToSql,
  validateErd,
  type ErdEntity,
  type ErdSchema,
} from '../src';

const ent = (id: string, name: string, cols: string[]): ErdEntity => ({
  id,
  name,
  logicalName: '',
  schema: '',
  comment: '',
  columns: cols.map((c) => parseColumn(c)!),
  indexes: [],
  uniqueConstraints: [],
  checks: [],
});

describe('ERD: parser cột', () => {
  it('email varchar(255) unique not null', () => {
    const c = parseColumn('email varchar(255) unique not null')!;
    expect(c).toMatchObject({ name: 'email', type: 'VARCHAR', length: 255, unique: true, nullable: false, pk: false });
  });

  it('pk, ai, default, check, comment, kiểu nhiều chữ, enum', () => {
    expect(parseColumn('id bigint pk ai')).toMatchObject({
      type: 'BIGINT',
      pk: true,
      nullable: false,
      autoIncrement: true,
    });
    expect(parseColumn("gia numeric(19,4) default 0 check (gia >= 0) comment 'Giá bán'")).toMatchObject({
      type: 'NUMERIC',
      precision: 19,
      scale: 4,
      default: '0',
      check: 'gia >= 0',
      comment: 'Giá bán',
      nullable: true,
    });
    expect(parseColumn('tao_luc timestamp with time zone not null')).toMatchObject({
      type: 'TIMESTAMP WITH TIME ZONE',
      nullable: false,
    });
    expect(parseColumn('ty_le double precision')).toMatchObject({ type: 'DOUBLE PRECISION' });
    expect(parseColumn("loai enum('XE_MAY','O_TO') not null")).toMatchObject({
      type: 'ENUM',
      enumValues: ['XE_MAY', 'O_TO'],
      nullable: false,
    });
    expect(parseColumn('ma int generated by default as identity primary key')).toMatchObject({
      type: 'INT',
      autoIncrement: true,
      pk: true,
    });
    expect(parseColumn('   ')).toBeNull();
  });

  it('format ↔ parse giữ nguyên, sửa lại giữ id / fk', () => {
    const c = parseColumn("ten nvarchar(100) unique not null default 'a''b' comment 'Tên'")!;
    const again = parseColumn(formatColumn(c), c)!;
    expect(again).toEqual(c);
    const fk = { relationshipId: 'r', refEntityId: 'e', refColumnId: 'k' };
    const edited = parseColumn('xe_id bigint not null', { ...c, fk })!;
    expect(edited.id).toBe(c.id);
    expect(edited.fk).toEqual(fk);
  });
});

describe('ERD: dialect', () => {
  it('bảng kiểu theo dialect', () => {
    expect(umlTypeToSql('String', 'postgresql')).toEqual({ type: 'VARCHAR', length: 255 });
    expect(umlTypeToSql('String', 'sqlserver')).toEqual({ type: 'NVARCHAR', length: 255 });
    expect(umlTypeToSql('boolean', 'mysql')).toEqual({ type: 'TINYINT', precision: 1 });
    expect(umlTypeToSql('LocalDateTime', 'postgresql')).toEqual({ type: 'TIMESTAMPTZ' });
    expect(umlTypeToSql('BigDecimal', 'mysql')).toEqual({ type: 'DECIMAL', precision: 19, scale: 4 });
    expect(umlTypeToSql('UUID', 'mysql')).toEqual({ type: 'CHAR', length: 36 });
    expect(umlTypeToSql('Map<String, Object>', 'postgresql')).toEqual({ type: 'JSONB' });
    expect(umlTypeToSql('Money', 'postgresql', { money: 'MONEY' })).toEqual({ type: 'MONEY' });
    expect(umlTypeToSql('ToaDo', 'postgresql')).toBeNull();
  });

  it('trích dẫn tên trùng từ khoá / ký tự đặc biệt', () => {
    expect(quoteIdent('user', 'postgresql')).toBe('"user"');
    expect(quoteIdent('order', 'mysql')).toBe('`order`');
    expect(quoteIdent('user', 'sqlserver')).toBe('[user]');
    expect(quoteIdent('phien_gui_xe', 'postgresql')).toBe('phien_gui_xe');
    expect(needsQuote('PhienGuiXe', 'postgresql')).toBe(true);
    expect(needsQuote('PhienGuiXe', 'mysql')).toBe(false);
    expect(needsQuote('so tien', 'sqlserver')).toBe(true);
  });
});

describe('ERD: quan hệ và khoá ngoại', () => {
  const xe = () => ent('xe', 'xe', ['id bigint pk ai', 'bien_so varchar(20) unique not null']);
  const phien = () => ent('p', 'phien_gui_xe', ['id bigint pk ai', 'gio_vao timestamptz not null']);

  it('One-to-Many: thêm <cha>_id kiểu = kiểu PK cha, NOT NULL', () => {
    const parent = xe();
    const r = addFkColumns(parent, phien(), {
      id: 'r1',
      kind: 'rel1n',
      identifying: false,
      parent: { cardinality: 'one' },
    });
    const fk = r.columns.find((c) => c.name === 'xe_id')!;
    expect(fk).toMatchObject({ type: 'BIGINT', nullable: false, unique: false, pk: false, autoIncrement: false });
    expect(fk.fk).toEqual({ relationshipId: 'r1', refEntityId: 'xe', refColumnId: parent.columns[0].id });
    expect(r.fkColumns).toEqual([{ childColumnId: fk.id, parentColumnId: fk.fk!.refColumnId }]);
  });

  it('One-to-One thêm UNIQUE; identifying đưa FK vào PK; cha chưa có PK báo noPk', () => {
    const r = addFkColumns(xe(), phien(), { id: 'r', kind: 'rel11', identifying: false });
    expect(r.columns.find((c) => c.name === 'xe_id')!.unique).toBe(true);
    const id = addFkColumns(xe(), ent('c', 'chi_tiet', ['so int pk']), { id: 'r', kind: 'rel1n', identifying: true });
    expect(id.columns.map((c) => [c.name, c.pk])).toEqual([
      ['so', true],
      ['xe_id', true],
    ]);
    expect(
      addFkColumns(ent('a', 'a', ['ten text']), phien(), { id: 'r', kind: 'rel1n', identifying: false }).noPk,
    ).toBe(true);
  });

  it('đổi tên/kiểu PK cha → FK con cập nhật theo', () => {
    const parent = xe();
    const child = { ...phien() };
    child.columns = addFkColumns(parent, child, { id: 'r', kind: 'rel1n', identifying: false }).columns;
    const renamed = { ...parent, columns: parent.columns.map((c) => (c.pk ? { ...c, name: 'ma', type: 'UUID' } : c)) };
    const cols = propagatePk(parent, renamed, child)!;
    expect(cols.find((c) => c.fk)).toMatchObject({ name: 'xe_ma', type: 'UUID' });
    expect(propagatePk(parent, parent, child)).toBeNull();
  });

  it('Many-to-Many → bảng trung gian a_b, PK ghép 2 FK', () => {
    const goi = ent('g', 'goi_thang', ['id uuid pk']);
    const j = buildJunction(goi, xe());
    expect(j.entity.name).toBe('goi_thang_xe');
    expect(j.entity.columns.map((c) => [c.name, c.type, c.pk])).toEqual([
      ['goi_thang_id', 'UUID', true],
      ['xe_id', 'BIGINT', true],
    ]);
    expect(j.relationships.map((r) => [r.parent.entityId, r.identifying, r.onDelete])).toEqual([
      ['g', true, 'CASCADE'],
      ['xe', true, 'CASCADE'],
    ]);
  });
});

describe('ERD: kiểm tra', () => {
  it('thiếu PK, trùng tên, FK sai kiểu/không phải PK, từ khoá, N-N', () => {
    const user = ent('u', 'user', ['id bigint pk', 'email text', 'order int']);
    const a = ent('a', 'Bang', ['ten text']);
    const b = ent('b', 'bang', ['id int pk', 'id int']);
    const c = ent('c', 'c', ['id int pk']);
    c.columns.push(
      newColumn('u_id', 'INT', { fk: { relationshipId: 'r', refEntityId: 'u', refColumnId: user.columns[0].id } }),
    );
    c.columns.push(
      newColumn('u_email', 'TEXT', { fk: { relationshipId: 'r2', refEntityId: 'u', refColumnId: user.columns[1].id } }),
    );
    const s: ErdSchema = {
      ...emptySchema(),
      entities: [user, a, b, c],
      relationships: [
        {
          id: 'nn',
          name: '',
          kind: 'relnn',
          identifying: false,
          parent: { entityId: 'a', cardinality: 'zeroOrOne' },
          child: { entityId: 'b', cardinality: 'zeroOrMany' },
          fkColumns: [],
          onDelete: 'NO ACTION',
          onUpdate: 'NO ACTION',
        },
      ],
    };
    const codes = validateErd(s, 'postgresql').map((i) => `${i.code}:${i.targetId}`);
    expect(codes).toEqual(
      expect.arrayContaining([
        'keyword:u',
        'no-pk:a',
        'dup-table:b',
        'dup-column:b',
        'fk-type:c',
        'fk-target:c',
        'nn:nn',
      ]),
    );
    expect(codes.filter((x) => x === 'keyword:u')).toHaveLength(2); // bảng user + cột order
  });
});

/** ERD nhỏ đủ loại: enum, FK vòng, tự tham chiếu, index, unique, check, view, sequence, comment. */
function sample(): ErdSchema {
  const loai = ent('l', 'loai', ['id int pk ai', 'ten varchar(50) not null unique']);
  const xe = ent('x', 'xe', [
    'id bigint pk ai',
    'bien_so varchar(20) not null unique',
    "loai_xe enum('XE_MAY','O_TO') not null default 'XE_MAY'",
    "gia numeric(19,4) default 0 check (gia >= 0) comment 'Giá gửi'",
  ]);
  xe.comment = 'Xe của sinh viên';
  const user = ent('u', 'user', ['id uuid pk ai', 'email varchar(255) not null', 'xe_ua_thich_id bigint']);
  const node = ent('n', 'danh_muc', ['id int pk ai', 'ten text not null']);
  const s: ErdSchema = { ...emptySchema(), entities: [xe, loai, user, node] };
  const link = (id: string, p: ErdEntity, c: ErdEntity, kind: 'rel1n' | 'rel11', role?: string) => {
    const r = addFkColumns(p, c, { id, kind, identifying: false, parent: { cardinality: 'zeroOrOne' } }, { role });
    c.columns = r.columns;
    s.relationships.push({
      id,
      name: '',
      kind,
      identifying: false,
      parent: { entityId: p.id, cardinality: 'zeroOrOne' },
      child: { entityId: c.id, cardinality: 'zeroOrMany' },
      fkColumns: r.fkColumns,
      onDelete: 'SET NULL',
      onUpdate: 'CASCADE',
    });
  };
  link('r1', loai, xe, 'rel1n');
  link('r2', user, xe, 'rel1n', 'chu');
  // vòng: user → xe và xe → user
  user.columns = user.columns.map((c) =>
    c.name === 'xe_ua_thich_id'
      ? { ...c, fk: { relationshipId: 'r3', refEntityId: 'x', refColumnId: xe.columns[0].id } }
      : c,
  );
  link('r4', node, node, 'rel1n', 'cha');
  user.indexes.push({ id: 'i1', name: 'ix_user_email', columns: [user.columns[1].id], unique: true });
  xe.uniqueConstraints.push({ id: 'u1', name: 'uq_xe_loai_bien', columns: ['loai_id', 'bien_so'] });
  xe.checks.push({ id: 'k1', name: 'ck_xe_bien_so', expr: "bien_so <> ''" });
  s.views.push({ id: 'v', name: 'v_xe', definition: 'SELECT id, bien_so FROM xe;', columns: [], comment: '' });
  s.sequences.push({ id: 's', name: 'seq_ma_the', start: 1000, increment: 1, cycle: false });
  return s;
}

describe('ERD: sinh DDL', () => {
  it('thứ tự topo: bảng không phụ thuộc trước, bỏ qua tự tham chiếu', () => {
    const s = sample();
    const names = topoOrder(s.entities).map((e) => e.name);
    expect(names.indexOf('loai')).toBeLessThan(names.indexOf('xe'));
  });

  it('PostgreSQL: enum, sequence, CREATE TABLE, FK tách riêng, index, view, comment', () => {
    const sql = erdToDdl(sample(), 'postgresql');
    expect(sql).toContain(`CREATE TYPE xe_loai_xe AS ENUM ('XE_MAY', 'O_TO');`);
    expect(sql).toContain('CREATE SEQUENCE seq_ma_the START WITH 1000 INCREMENT BY 1 NO CYCLE;');
    expect(sql).toContain('CREATE TABLE "user" (');
    expect(sql).toContain('id UUID DEFAULT gen_random_uuid() NOT NULL');
    expect(sql).toContain('id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(sql).toContain(
      'ALTER TABLE xe ADD CONSTRAINT fk_xe_loai FOREIGN KEY (loai_id) REFERENCES loai (id) ON DELETE SET NULL ON UPDATE CASCADE;',
    );
    expect(sql).toContain('CREATE UNIQUE INDEX ix_user_email ON "user" (email);');
    expect(sql).toContain("COMMENT ON COLUMN xe.gia IS 'Giá gửi';");
    expect(sql.indexOf('CREATE TABLE')).toBeLessThan(sql.indexOf('ALTER TABLE'));
  });

  it('MySQL / SQL Server: trích dẫn, AUTO_INCREMENT / IDENTITY, ENUM / CHECK IN, COMMENT', () => {
    const my = erdToDdl(sample(), 'mysql');
    expect(my).toContain('CREATE TABLE `user` (');
    expect(my).toContain('id BIGINT AUTO_INCREMENT NOT NULL');
    expect(my).toContain("loai_xe ENUM('XE_MAY', 'O_TO') NOT NULL DEFAULT 'XE_MAY'");
    expect(my).toContain(") COMMENT = 'Xe của sinh viên';");
    expect(my).toContain('-- MySQL không có SEQUENCE');
    const ms = erdToDdl(sample(), 'sqlserver');
    expect(ms).toContain('CREATE TABLE [user] (');
    expect(ms).toContain('id BIGINT IDENTITY(1,1) NOT NULL');
    expect(ms).toContain("CHECK (loai_xe IN ('XE_MAY', 'O_TO'))");
    expect(ms).toContain("EXEC sp_addextendedproperty 'MS_Description', N'Xe của sinh viên'");
  });

  it('DDL PostgreSQL chạy được trên Postgres thật (PGlite)', async () => {
    const db = new PGlite();
    await db.exec(erdToDdl(sample(), 'postgresql'));
    const r = await db.query<{ table_name: string }>(
      `SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' ORDER BY 1`,
    );
    expect(r.rows.map((x) => x.table_name)).toEqual(['danh_muc', 'loai', 'user', 'v_xe', 'xe']);
    const fk = await db.query(
      `SELECT count(*)::int AS n FROM information_schema.table_constraints WHERE constraint_type = 'FOREIGN KEY'`,
    );
    expect(fk.rows[0]).toEqual({ n: 4 });
    await db.close();
  }, 60_000);
});
