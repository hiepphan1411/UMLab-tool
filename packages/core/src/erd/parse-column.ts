// Parser / formatter một dòng cột ERD: `email varchar(255) unique not null default 'a' comment 'Email đăng nhập'`.
// Cờ nhận được: pk | primary key, not null | nn | null, unique | uq, ai | auto_increment | identity,
// default <biểu thức>, check (<biểu thức>), comment '<chú thích>'. Kiểu `enum('A','B')` → cột enum.
import { parseTypeText, typeText } from './dialect';
import { newColumn, type ErdColumn } from './model';

/** Tách theo khoảng trắng, giữ nguyên phần trong ngoặc đơn và chuỗi '…'. */
function tokens(s: string): string[] {
  const out: string[] = [];
  let cur = '';
  let depth = 0;
  let quote = false;
  for (const ch of s) {
    if (quote) {
      cur += ch;
      if (ch === "'") quote = false;
      continue;
    }
    if (ch === "'") {
      quote = true;
      cur += ch;
      continue;
    }
    if (ch === '(') depth++;
    if (ch === ')') depth = Math.max(0, depth - 1);
    if (/\s/.test(ch) && depth === 0) {
      if (cur) out.push(cur);
      cur = '';
    } else cur += ch;
  }
  if (cur) out.push(cur);
  return out;
}

const unquote = (s: string) => (s.startsWith("'") && s.endsWith("'") ? s.slice(1, -1).replace(/''/g, "'") : s);
const unparen = (s: string) => (s.startsWith('(') && s.endsWith(')') ? s.slice(1, -1).trim() : s);
const unident = (s: string) => s.replace(/^["`[]|["`\]]$/g, '');

/** Từ ghép thành kiểu nhiều chữ: double precision, character varying, timestamp with time zone. */
function takeType(t: string[], i: number): { text: string; next: number } {
  let text = t[i];
  let j = i + 1;
  const low = (k: number) => (t[k] ?? '').toLowerCase();
  if (/^double$/i.test(text) && low(j) === 'precision') text += ' ' + t[j++];
  else if (/^(character|bit)$/i.test(text) && low(j).startsWith('varying')) text += ' ' + t[j++];
  else if (/^(timestamp|time)/i.test(text) && (low(j) === 'with' || low(j) === 'without') && low(j + 1) === 'time') {
    text += ' ' + t.slice(j, j + 3).join(' ');
    j += 3;
  }
  if ((t[j] ?? '').startsWith('(')) text += t[j++];
  return { text, next: j };
}

/** Phân tích một dòng cột. `prev` giữ id/fk/mappedFrom khi sửa lại dòng cũ. null nếu dòng rỗng. */
export function parseColumn(text: string, prev?: Partial<ErdColumn>): ErdColumn | null {
  const t = tokens(text.trim().replace(/,$/, ''));
  if (!t.length) return null;
  const name = unident(t[0]);
  const base = newColumn(name, 'VARCHAR');
  const col: ErdColumn = {
    ...base,
    id: prev?.id ?? base.id,
    ...(prev?.fk ? { fk: prev.fk } : {}),
    ...(prev?.mappedFrom ? { mappedFrom: prev.mappedFrom } : {}),
    ...(prev?.logicalName ? { logicalName: prev.logicalName } : {}),
  };
  let i = 1;
  if (t[1]) {
    const { text: ty, next } = takeType(t, 1);
    i = next;
    const en = ty.match(/^enum\s*\((.*)\)$/i);
    if (en) {
      col.type = prev?.enumValues && prev.type ? prev.type : 'ENUM';
      col.enumValues = en[1]
        .split(',')
        .map((x) => unquote(x.trim()))
        .filter(Boolean);
    } else if (prev?.enumValues?.length && ty === prev.type) {
      col.type = prev.type;
      col.enumValues = prev.enumValues;
    } else {
      const st = parseTypeText(ty);
      col.type = st.type;
      if (st.length !== undefined) col.length = st.length;
      if (st.precision !== undefined) col.precision = st.precision;
      if (st.scale !== undefined) col.scale = st.scale;
    }
  } else if (prev?.type) {
    // chỉ gõ tên → giữ kiểu cũ
    Object.assign(col, {
      type: prev.type,
      length: prev.length,
      precision: prev.precision,
      scale: prev.scale,
      enumValues: prev.enumValues,
    });
  }
  let nullSet = false;
  while (i < t.length) {
    const w = t[i].toLowerCase();
    const nx = (t[i + 1] ?? '').toLowerCase();
    if (w === 'pk' || (w === 'primary' && nx === 'key')) {
      col.pk = true;
      i += w === 'pk' ? 1 : 2;
    } else if ((w === 'not' && nx === 'null') || w === 'nn') {
      col.nullable = false;
      nullSet = true;
      i += w === 'nn' ? 1 : 2;
    } else if (w === 'null') {
      col.nullable = true;
      nullSet = true;
      i++;
    } else if (w === 'unique' || w === 'uq') {
      col.unique = true;
      i++;
    } else if (
      w === 'ai' ||
      w === 'auto_increment' ||
      w === 'autoincrement' ||
      w.startsWith('identity') ||
      (w === 'generated' && nx)
    ) {
      col.autoIncrement = true;
      // GENERATED BY DEFAULT AS IDENTITY / GENERATED ALWAYS AS IDENTITY
      if (w === 'generated') {
        const end = t.findIndex((x, k) => k > i && /^identity/i.test(x));
        i = end > 0 ? end + 1 : i + 1;
      } else i++;
    } else if (w === 'default' && i + 1 < t.length) {
      col.default = t[i + 1];
      i += 2;
    } else if (w === 'check' && i + 1 < t.length) {
      col.check = unparen(t[i + 1]);
      i += 2;
    } else if (w === 'comment' && i + 1 < t.length) {
      col.comment = unquote(t[i + 1]);
      i += 2;
    } else i++;
  }
  if (col.pk) col.nullable = false;
  else if (!nullSet && prev && prev.nullable === false && prev.pk) col.nullable = false;
  return col;
}

/** Dòng sửa (ngược lại của parseColumn). */
export function formatColumn(c: ErdColumn): string {
  const parts = [c.name];
  parts.push(
    c.enumValues?.length
      ? `enum(${c.enumValues.map((v) => `'${v.replace(/'/g, "''")}'`).join(',')})`
      : typeText(c).toLowerCase(),
  );
  if (c.pk) parts.push('pk');
  else if (!c.nullable) parts.push('not null');
  if (c.unique && !c.pk) parts.push('unique');
  if (c.autoIncrement) parts.push('ai');
  if (c.default) parts.push('default ' + c.default);
  if (c.check) parts.push(`check (${c.check})`);
  if (c.comment) parts.push(`comment '${c.comment.replace(/'/g, "''")}'`);
  return parts.join(' ');
}
